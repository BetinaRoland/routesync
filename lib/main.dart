Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  Object? startupError;
  try {
    await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  } catch (e) {
    startupError = e;
  }
  runApp(startupError == null ? const BusApp() : StartupError(error: startupError));
}

/// Shown instead of a blank page when Firebase cannot start.
class StartupError extends StatelessWidget {
  final Object error;
  const StartupError({super.key, required this.error});
  @override
  Widget build(BuildContext context) => MaterialApp(
        theme: buildTheme(),
        debugShowCheckedModeBanner: false,
        home: Scaffold(
          body: Center(
            child: Padding(
              padding: const EdgeInsets.all(28),
              child: Column(mainAxisSize: MainAxisSize.min, children: [
                const Icon(Icons.cloud_off, size: 44, color: navy),
                const SizedBox(height: 14),
                const Text('RouteSync could not connect to Firebase', style: TextStyle(fontSize: 18, fontWeight: FontWeight.w600), textAlign: TextAlign.center),
                const SizedBox(height: 8),
                const Text('Check that lib/firebase_options.dart exists for project routesync-94a88, then restart the app.', textAlign: TextAlign.center),
                const SizedBox(height: 14),
                SelectableText('$error', style: const TextStyle(fontSize: 12), textAlign: TextAlign.center),
              ]),
            ),
          ),
        ),
      );
}

class BusApp extends StatelessWidget {
  const BusApp({super.key});
  @override
  Widget build(BuildContext context) => MaterialApp(title: 'RouteSync', theme: buildTheme(), darkTheme: buildTheme(Brightness.dark), themeMode: ThemeMode.system, debugShowCheckedModeBanner: false, home: const AuthGate());
}

class AuthGate extends StatelessWidget {
  const AuthGate({super.key});
  @override
  Widget build(BuildContext context) => StreamBuilder<User?>(
        stream: FirebaseAuth.instance.authStateChanges(),
        builder: (context, snap) {
          if (snap.connectionState == ConnectionState.waiting) return const Scaffold(body: Center(child: CircularProgressIndicator()));
          final user = snap.data;
          if (user == null) {
            final code = Uri.base.queryParameters['code']; // from an invitation link or QR code
            return (code != null && code.isNotEmpty) ? RegisterPage(initialCode: code) : const LoginPage();
          }
          return FutureBuilder<Session>(
            key: ValueKey(user.uid),
            future: Session.load(user),
            builder: (context, s) {
              if (s.hasError) return _Pending(message: 'Could not load your account. Check your connection.');
              if (!s.hasData) return const Scaffold(body: Center(child: CircularProgressIndicator()));
              return switch (s.data!.role) {
                Role.superAdmin => SessionGuard(role: Role.superAdmin, child: AdminShell(session: s.data!, title: 'Super Admin')),
                Role.routeAdmin => SessionGuard(role: Role.routeAdmin, child: AdminShell(session: s.data!, title: 'Route Admin')),
                Role.driver => SessionGuard(role: Role.driver, child: DriverHome(session: s.data!)),
                Role.student => SessionGuard(role: Role.student, child: StudentHome(session: s.data!)),
                Role.unknown => _Pending(message: s.data!.disabled ? 'This account has been disabled. Contact the college transport office.' : 'Your account has no role yet. Ask the Route Admin to activate it.'),
              };
            },
          );
        },
      );
}

class _Pending extends StatelessWidget {
  final String message;
  const _Pending({required this.message});
  @override
  Widget build(BuildContext context) => Scaffold(
        appBar: AppBar(title: const Text('Access pending')),
        body: Center(
          child: Padding(
            padding: const EdgeInsets.all(24),
            child: Column(mainAxisSize: MainAxisSize.min, children: [
              Text(message, textAlign: TextAlign.center),
              const SizedBox(height: 16),
              FilledButton(onPressed: () => FirebaseAuth.instance.signOut(), child: const Text('Sign out')),
            ]),
          ),
        ),
      );
}
